#!/usr/bin/env bash
# Make the AWS Workshop Studio "K8s Agentic Platform" labs runnable against THIS stack.
#
# The labs assume an event-provisioned environment: the starter-kit checked out at /workshop,
# /workshop/.env with credentials, public Ingress URLs, Terraform outputs next to the components.
# This script rebuilds just enough of that locally, with nothing exposed publicly:
#
#   setup      shallow-checkout the starter-kit at the pinned commit into .workshop/starter-kit, write its
#              .env from the Terraform outputs, and render components/ai-gateway/litellm/values.rendered.yaml
#              from the running LiteLLM release (the A1 lab edits that file and runs `helm upgrade`)
#   env        print `export ...` lines; use:  eval "$(scripts/workshop.sh env)"
#   pf-start   keep Open WebUI / LiteLLM / Langfuse reachable on 127.0.0.1 (auto-restarting port-forwards)
#   pf-stop    stop them
#   status     what is set up and what is listening
#
# To make the pages' absolute /workshop paths work verbatim (needs root, your decision):
#   sudo ln -s "$PWD/.workshop/starter-kit" /workshop
#
# Everything under .workshop/ is git-ignored and may contain credentials (mode 600/700).
# Works with the macOS default bash 3.2.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WS="$ROOT/.workshop"
KIT="$WS/starter-kit"
KIT_URL="https://github.com/aws-samples/sample-genai-on-eks-starter-kit.git"
KIT_REF="${KIT_REF:-0052c58850310d0eadd7aca769dfee3e5dad7a11}"  # main @ 2026-10-15, what the labs were checked against
export KUBECONFIG="${KUBECONFIG:-$ROOT/.kubeconfig}"

die() { echo "error: $*" >&2; exit 1; }
tf() { terraform -chdir="$ROOT" "$@"; }

need() { command -v "$1" >/dev/null 2>&1 || die "$1 is required"; }

cmd_setup() {
  need git; need terraform; need python3; need helm; need kubectl
  [ -f "$KUBECONFIG" ] || die "no kubeconfig at $KUBECONFIG - run: make kubeconfig"
  tf output -raw cluster_name >/dev/null 2>&1 || die "no Terraform outputs yet - run: make apply"

  mkdir -p "$WS" && chmod 700 "$WS"

  if [ ! -d "$KIT/.git" ]; then
    echo "==> fetching starter-kit @ ${KIT_REF:0:7} into $KIT"
    mkdir -p "$KIT"
    git -C "$KIT" init -q
    git -C "$KIT" remote add origin "$KIT_URL"
    git -C "$KIT" fetch -q --depth 1 origin "$KIT_REF"
    git -C "$KIT" checkout -q --detach FETCH_HEAD
  else
    echo "==> starter-kit already present ($(git -C "$KIT" rev-parse --short HEAD))"
  fi

  echo "==> writing $KIT/.env (mode 600)"
  write_env

  echo "==> rendering components/ai-gateway/litellm/values.rendered.yaml from the live release (mode 600)"
  write_values

  cat <<EOF

Ready. In every terminal where you follow the labs:

    cd $ROOT
    make pf-start                              # once: Open WebUI :8000, LiteLLM :4000, Langfuse :3000 on 127.0.0.1
    eval "\$(scripts/workshop.sh env)"          # PATH shims, \$WORKSHOP_DIR, \$KUBECONFIG, .env variables

Labs refer to /workshop/...; use \$WORKSHOP_DIR/... instead, or (needs sudo, your call):
    sudo ln -s "$KIT" /workshop
EOF
}

write_env() {
  local creds
  creds="$(tf output -json credentials)"
  CREDS_JSON="$creds" \
  REGION_V="$(tf output -raw region)" CLUSTER_V="$(tf output -raw cluster_name)" \
  OUT="$KIT/.env" python3 - <<'PY'
import json, os, shlex
c = json.loads(os.environ["CREDS_JSON"])
region, cluster = os.environ["REGION_V"], os.environ["CLUSTER_V"]
rows = [
    ("PLATFORM", "eks"), ("EKS_MODE", "auto"),
    ("REGION", region), ("AWS_REGION", region),
    ("EKS_CLUSTER_NAME", cluster), ("CLUSTER_NAME", cluster), ("DOMAIN", ""),
    # LiteLLM: the labs say "log in with the value of LITELLM_MASTER_KEY"; this stack also has a separate UI password
    ("LITELLM_MASTER_KEY", c["litellm_master_key"]), ("LITELLM_API_KEY", c["litellm_master_key"]),
    ("LITELLM_UI_USERNAME", c["litellm_ui_user"]), ("LITELLM_UI_PASSWORD", c["litellm_ui_password"]),
    ("LANGFUSE_USERNAME", c["admin_email"]), ("LANGFUSE_PASSWORD", c["langfuse_password"]),
    ("LANGFUSE_PUBLIC_KEY", c["langfuse_public_key"]), ("LANGFUSE_SECRET_KEY", c["langfuse_secret_key"]),
    ("OPENWEBUI_ADMIN_EMAIL", c["admin_email"]), ("OPENWEBUI_ADMIN_PASSWORD", c["openwebui_password"]),
    # loopback URLs served by `make pf-start`
    ("LITELLM_URL", "http://127.0.0.1:4000"), ("LANGFUSE_URL", "http://127.0.0.1:3000"),
    ("OPENWEBUI_URL", "http://127.0.0.1:8000"),
]
# keep what the labs appended (the Virtual Key step writes AGENT_KEY here)
keep = []
if os.path.exists(os.environ["OUT"]):
    with open(os.environ["OUT"]) as old_f:
        keep = [ln.rstrip("\n") for ln in old_f if ln.startswith("AGENT_KEY=")]

old = os.umask(0o077)
with open(os.environ["OUT"], "w") as f:
    f.write("# Generated by scripts/workshop.sh from this stack's Terraform outputs. Contains credentials.\n")
    f.write("# AGENT_KEY is added by the labs (Virtual Key step); it is kept when this file is regenerated.\n")
    for k, v in rows:
        f.write("%s=%s\n" % (k, shlex.quote(v)))
    for ln in keep:
        f.write(ln + "\n")
os.umask(old)
PY
  chmod 600 "$KIT/.env"
}

write_values() {
  local out="$KIT/components/ai-gateway/litellm"
  mkdir -p "$out"
  # Never clobber what the A1 lab edited; regenerate on purpose with FORCE_VALUES=1
  if [ -f "$out/values.rendered.yaml" ] && [ -z "${FORCE_VALUES:-}" ]; then
    echo "    kept existing values.rendered.yaml (FORCE_VALUES=1 make workshop-setup to regenerate)"
    return 0
  fi
  VALUES_JSON="$(helm -n litellm get values litellm -o json)" OUT="$out/values.rendered.yaml" python3 - <<'PY'
import json, os
import yaml  # PyYAML

v = json.loads(os.environ["VALUES_JSON"])
# The lab greps "model_name.*bedrock" with -A 3, so keep model_name first in each entry
ml = v.get("proxy_config", {}).get("model_list", [])
v["proxy_config"]["model_list"] = [
    dict([("model_name", m["model_name"])] + [(k, x) for k, x in m.items() if k != "model_name"]) for m in ml
]

class D(yaml.SafeDumper):
    def increase_indent(self, flow=False, indentless=False):  # indent list items under their key, as in the labs
        return super().increase_indent(flow, False)

old = os.umask(0o077)
with open(os.environ["OUT"], "w") as f:
    f.write("# Generated by scripts/workshop.sh from `helm get values litellm -n litellm`. Contains credentials.\n")
    f.write("# The A1 lab edits the Bedrock model list here and runs `helm upgrade litellm ... -f` on this file.\n")
    yaml.dump(v, f, Dumper=D, default_flow_style=False, sort_keys=False, indent=2, width=1000)
os.umask(old)
PY
  chmod 600 "$out/values.rendered.yaml"
}

cmd_env() {
  [ -f "$KIT/.env" ] || die "run scripts/workshop.sh setup first"
  cat <<EOF
export WORKSHOP_STACK_DIR='$ROOT'
export WORKSHOP_DIR='$KIT'
export KUBECONFIG='$KUBECONFIG'
case ":\$PATH:" in *":$ROOT/scripts/workshop-shim:"*) ;; *) export PATH='$ROOT/scripts/workshop-shim':"\$PATH" ;; esac
set -a; . '$KIT/.env'; set +a
EOF
}

# Create the lab's "agent-key" Virtual Key through the LiteLLM API (the labs do it in the UI) and store it as
# AGENT_KEY in the workshop .env. The key value is never printed. Models default to what this stack serves;
# add bedrock/gpt-oss-20b (A1 lab) with AGENT_KEY_MODELS=...
cmd_agent_key() {
  need curl; need python3
  [ -f "$KIT/.env" ] || die "run scripts/workshop.sh setup first"
  curl -s -m 5 -o /dev/null http://127.0.0.1:4000/health/readiness || die "LiteLLM is not reachable on 127.0.0.1:4000 - run: make pf-start"
  KIT_ENV="$KIT/.env" ALIAS="${AGENT_KEY_ALIAS:-agent-key-cli}" MODELS="${AGENT_KEY_MODELS:-bedrock/claude-4.5-sonnet,vllm/qwen3-8b-neuron,vllm/deepseek-r1-qwen3-8b-neuron}" python3 - <<'PY'
import json, os, shlex, urllib.request

env_path = os.environ["KIT_ENV"]
env = {}
with open(env_path) as f:
    for line in f:
        if "=" in line and not line.startswith("#"):
            k, v = line.rstrip("\n").split("=", 1)
            env[k] = shlex.split(v)[0] if v else ""
master = env["LITELLM_MASTER_KEY"]
alias_ = os.environ.get("ALIAS", "agent-key-cli")
body = json.dumps({"key_alias": alias_, "models": os.environ["MODELS"].split(",")}).encode()
req = urllib.request.Request("http://127.0.0.1:4000/key/generate", data=body,
                             headers={"Authorization": "Bearer " + master, "Content-Type": "application/json"})
try:
    key = json.load(urllib.request.urlopen(req, timeout=30))["key"]
except urllib.error.HTTPError as e:
    # error bodies never contain the new key, so the message is safe to show
    msg = ""
    try:
        msg = json.load(e).get("error", {}).get("message", "")
    except Exception:
        pass
    hint = ""
    if "already exists" in msg:
        hint = " (a key with that alias exists, e.g. one made in the UI; it is left untouched - set AGENT_KEY_ALIAS to another name)"
    raise SystemExit("key/generate failed: HTTP %s %s%s" % (e.code, msg[:200], hint))
except Exception as e:
    raise SystemExit("key/generate failed: %s" % type(e).__name__)
lines = [l for l in open(env_path).read().splitlines() if not l.startswith("AGENT_KEY=")]
old = os.umask(0o077)
with open(env_path, "w") as f:
    f.write("\n".join(lines) + "\nAGENT_KEY=" + shlex.quote(key) + "\n")
os.umask(old)
print("AGENT_KEY stored in .env (%s..., models: %s)" % (key[:6], os.environ["MODELS"]))
PY
  chmod 600 "$KIT/.env"
}

PF_SPECS="openwebui:openwebui:8000:80 litellm:litellm:4000:4000 langfuse:langfuse-web:3000:3000 grafana:grafana:3001:3000"  # ns:svc:local:remote

cmd_pf_start() {
  need kubectl; need lsof
  mkdir -p "$WS" && chmod 700 "$WS"
  [ -f "$KUBECONFIG" ] || die "no kubeconfig at $KUBECONFIG - run: make kubeconfig"
  if [ -s "$WS/pf.pids" ]; then die "port-forwards already started (pids in $WS/pf.pids); run: make pf-stop"; fi
  : > "$WS/pf.pids"
  local spec ns svc lport rport
  for spec in $PF_SPECS; do
    IFS=: read -r ns svc lport rport <<EOF
$spec
EOF
    if lsof -nP -iTCP:"$lport" -sTCP:LISTEN >/dev/null 2>&1; then
      echo "skip: 127.0.0.1:$lport is already in use ($ns/$svc)"; continue
    fi
    # a plain loop so the forward comes back after a pod restart (e.g. after the A1 `helm upgrade`)
    nohup bash -c "while true; do kubectl -n '$ns' port-forward --address 127.0.0.1 svc/$svc $lport:$rport >/dev/null 2>&1; sleep 2; done" \
      >/dev/null 2>&1 < /dev/null &
    echo $! >> "$WS/pf.pids"
    echo "started: $ns/$svc -> 127.0.0.1:$lport"
  done
}

cmd_pf_stop() {
  local pid
  if [ -s "$WS/pf.pids" ]; then
    while read -r pid; do [ -n "$pid" ] && kill "$pid" 2>/dev/null || true; done < "$WS/pf.pids"
  fi
  : > "$WS/pf.pids" 2>/dev/null || true
  # the loop's current kubectl child; match tightly (loopback bind + our services)
  pkill -f 'kubectl -n (openwebui|litellm|langfuse|grafana) port-forward --address 127.0.0.1 svc/(openwebui|litellm|langfuse-web|grafana) ' 2>/dev/null || true
  echo "port-forwards stopped"
}

cmd_status() {
  echo "starter-kit:  $( [ -d "$KIT/.git" ] && git -C "$KIT" rev-parse --short HEAD || echo 'not set up (run: make workshop-setup)')"
  echo ".env:         $( [ -f "$KIT/.env" ] && echo present || echo missing)"
  echo "values.rendered.yaml: $( [ -f "$KIT/components/ai-gateway/litellm/values.rendered.yaml" ] && echo present || echo missing)"
  echo "listening on loopback:"
  lsof -nP -iTCP:8000 -iTCP:4000 -iTCP:3000 -iTCP:8888 -sTCP:LISTEN 2>/dev/null | awk 'NR>1{print "  " $1, $9}' || true
}

case "${1:-}" in
  setup)    cmd_setup ;;
  env)      cmd_env ;;
  pf-start) cmd_pf_start ;;
  pf-stop)  cmd_pf_stop ;;
  status)   cmd_status ;;
  agent-key) cmd_agent_key ;;
  *) echo "usage: $0 setup | env | pf-start | pf-stop | status | agent-key" >&2; exit 64 ;;
esac
